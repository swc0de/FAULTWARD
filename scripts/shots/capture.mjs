// Fixed camera shots and render metrics for every map, so each graphics phase can be compared with the last.
//
//   node scripts/shots/capture.mjs plan
//       Works out the shot list from the map files and the baked instances (scripts/shots/shots.json, committed:
//       every phase uses the same cameras). Run it again only when a map's layout changes.
//
//   node scripts/shots/capture.mjs run --phase <name> [--maps qalat,bazaar] [--only wide,wall] [--seconds 20]
//                                       [--base http://127.0.0.1:5000] [--width 1920 --height 1080] [--gpu]
//       Starts a 5v5 bot "watch" match per map on a running server, puts the free-fly camera on every shot and
//       saves shots/<phase>/<map>/<shot>.jpg (the game canvas only, no HUD) plus shots/<phase>/metrics.json:
//       frame time (average and 1% low over --seconds), draw calls, triangles, texture count and an estimate of
//       the texture memory the scene's materials hold.
//
// Without --gpu Chromium renders with SwiftShader (software). Its frame times say nothing about a real GPU;
// compare them only with other SwiftShader runs. Draw calls, triangles and texture memory are the same either way.
//
// Shot kinds (8 per map): wide (overview), street (eye level outside), interior, wall (a wall at 1 m),
// vehicle (a parked vehicle at 5 m), char3 / char10 (an attacker bot at 3 m and 10 m), site (a bomb site).
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const PLAN = path.join(ROOT, "scripts", "shots", "shots.json");
const args = process.argv.slice(2);
const cmd = args[0];
const opt = (name, d) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : d;
};
const flag = (name) => args.includes(`--${name}`);
const say = (m) => process.stderr.write(`${m}\n`);
const MAPS = ["qalat", "bazaar", "oilcamp", "farmhouse"];

// Which of the map's own camera_shots stands for each kind (the rest are worked out below).
const PICK = {
  qalat: { wide: "overview", street: "bazaar", interior: "a_site", site: "b_site" },
  bazaar: { wide: "overview", street: "carpet_lane", interior: "a_site", site: "b_site" },
  oilcamp: { wide: "overview", street: "gate", interior: "a_floor", site: "b_separators" },
  farmhouse: { wide: "overview", street: "front", interior: "kitchen", site: "family" }
};

// ------------------------------------------------------------------------------------------------ plan
function hprMatrix(h, p, r = 0) {
  const D = Math.PI / 180;
  const ch = Math.cos(h * D), sh = Math.sin(h * D), cp = Math.cos(p * D), sp = Math.sin(p * D), cr = Math.cos(r * D), sr = Math.sin(r * D);
  return [
    [cr * ch - sr * sp * sh, cr * sh + sr * sp * ch, -sr * cp],
    [-cp * sh, cp * ch, sp],
    [sr * ch + cr * sp * sh, sr * sh - cr * sp * ch, cr * cp]
  ];
}

/** Distance along unit ray d from o to the first collider box, or Infinity. */
function rayBoxes(boxes, o, d, maxDist = 200) {
  let best = Infinity;
  for (const b of boxes) {
    if (b.size[0] > 200 || b.size[1] > 200) continue; // ground slab
    const R = b.R ?? (b.R = hprMatrix(b.hpr[0], b.hpr[1], b.hpr[2]));
    const rel = [o[0] - b.c[0], o[1] - b.c[1], o[2] - b.c[2]];
    let t0 = 0, t1 = maxDist, ok = true;
    for (let a = 0; a < 3 && ok; a++) {
      const ol = rel[0] * R[a][0] + rel[1] * R[a][1] + rel[2] * R[a][2];
      const dl = d[0] * R[a][0] + d[1] * R[a][1] + d[2] * R[a][2];
      const h = b.size[a] / 2;
      if (Math.abs(dl) < 1e-9) {
        if (Math.abs(ol) > h) ok = false;
        continue;
      }
      let ta = (-h - ol) / dl, tb = (h - ol) / dl;
      if (ta > tb) [ta, tb] = [tb, ta];
      t0 = Math.max(t0, ta);
      t1 = Math.min(t1, tb);
      if (t0 > t1) ok = false;
    }
    if (ok && t0 > 1e-4 && t0 < best) best = t0;
  }
  return best;
}

async function loadLevelCode() {
  // the same trick as scripts/bake-map.mjs: the shared level code lives in the bundled match worker
  const src = fs.readFileSync(path.join(ROOT, "server", "dist", "worker.mjs"), "utf8");
  const cut = src.lastIndexOf("// server/src/match/worker.ts");
  const tmp = path.join(ROOT, "server", "dist", `.shots-level-${process.pid}.mjs`);
  fs.writeFileSync(tmp, `${src.slice(0, cut)}\nexport { Level };\n`);
  try {
    return await import(pathToFileURL(tmp).href);
  } finally {
    fs.rmSync(tmp, { force: true });
  }
}

async function plan() {
  const { Level } = await loadLevelCode();
  const ga = JSON.parse(fs.readFileSync(path.join(ROOT, "client", "dist", "game-assets.json"), "utf8"));
  const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, "client", "dist", ga.manifest.replace(/^\//, "")), "utf8"));
  const out = { note: "Generated by scripts/shots/capture.mjs plan. yaw/pitch in degrees (yaw 0 looks along +Y, positive turns left).", maps: {} };
  for (const key of MAPS) {
    const data = JSON.parse(fs.readFileSync(path.join(ROOT, "data", "maps", `${key}.json`), "utf8"));
    const level = new Level(key, data, false);
    const boxes = [...level.ctx.colliders, ...level.ctx.panels.map((p) => ({ c: p.center, size: p.size, hpr: p.hpr }))];
    const entry = manifest.maps[key];
    const inst = JSON.parse(fs.readFileSync(path.join(ROOT, "client", "dist", entry.instances.replace(/^\//, "")), "utf8"));
    const nearVehicle = (c) => inst.some((i) => i.family === "vehicle" && Math.hypot(c[0] - i.base[0], c[1] - i.base[1]) < 4);
    const walls = boxes.filter((b) => !nearVehicle(b.c));
    const named = Object.fromEntries((data.camera_shots ?? []).map((s) => [s.name, s]));
    const pick = PICK[key];
    const shots = [];
    const fromNamed = (kind, name) => {
      const s = named[name];
      if (!s) throw new Error(`${key}: camera_shot ${name} not found`);
      shots.push({ kind, from: name, pos: s.pos, yaw: s.hpr[0], pitch: s.hpr[1] });
    };
    fromNamed("wide", pick.wide);
    fromNamed("street", pick.street);
    fromNamed("interior", pick.interior);
    // wall: walk along the street shot's heading to the first wall and stand 1 m in front of it (from the
    // street, not inside: furniture is visual only, so a ray indoors can stop inside a cupboard)
    {
      const s = named[pick.street];
      let found = null;
      for (let dh = 0; dh < 360 && !found; dh += 15) {
        for (const sgn of dh ? [1, -1] : [1]) {
          const yaw = s.hpr[0] + sgn * dh;
          const f = hprMatrix(yaw, 0)[1];
          const o = [s.pos[0], s.pos[1], s.pos[2] - 0.15];
          const d = rayBoxes(walls, o, f);
          if (d > 1.6 && d < 25) {
            found = { kind: "wall", from: `${pick.street} +${sgn * dh}deg`, pos: [o[0] + f[0] * (d - 1), o[1] + f[1] * (d - 1), o[2]].map((v) => Math.round(v * 100) / 100), yaw, pitch: -4 };
            break;
          }
        }
      }
      if (!found) throw new Error(`${key}: no wall found from ${pick.street}`);
      shots.push(found);
    }
    // vehicle: the first parked vehicle inside the bounds, from the first side with a clear 5 m line of sight
    {
      const [bmin, bmax] = data.bounds;
      const inside = (p) => p[0] > bmin[0] + 3 && p[0] < bmax[0] - 3 && p[1] > bmin[1] + 3 && p[1] < bmax[1] - 3;
      const cars = inst.filter((i) => i.family === "vehicle" && inside(i.base));
      cars.sort((a, b) => (b.wreck ? 0 : 1) - (a.wreck ? 0 : 1) || /boxcar|lorry|truck/.test(b.kind) - /boxcar|lorry|truck/.test(a.kind));
      let found = null;
      for (const car of cars) {
        for (const off of [35, -35, 145, -145, 90, -90, 0, 180]) {
          const yawFrom = car.heading + off;
          const dir = hprMatrix(yawFrom, 0)[1];
          const target = [car.base[0], car.base[1], car.base[2] + 0.9];
          const cam = [target[0] + dir[0] * 5, target[1] + dir[1] * 5, car.base[2] + 1.65];
          const back = [-dir[0], -dir[1], 0];
          const d = rayBoxes(boxes, cam, back, 5);
          if (d < 2.6) continue; // something other than the car itself is in the way
          const yaw = Math.atan2(-back[0], back[1]) * (180 / Math.PI);
          found = { kind: "vehicle", from: `${car.model} @${car.base.join(",")}`, pos: cam.map((v) => Math.round(v * 100) / 100), yaw: Math.round(yaw * 10) / 10, pitch: -8 };
          break;
        }
        if (found) break;
      }
      if (!found) say(`[plan] ${key}: no vehicle shot`);
      else shots.push(found);
    }
    // characters: an attacker bot, followed live from the attackers' side of the map (looking back at it)
    shots.push({ kind: "char3", follow: "attack", distance: 3, height: 1.6, pitch: -4 });
    shots.push({ kind: "char10", follow: "attack", distance: 10, height: 2.2, pitch: -6 });
    fromNamed("site", pick.site);
    out.maps[key] = shots;
    say(`[plan] ${key}: ${shots.map((s) => s.kind).join(", ")}`);
  }
  fs.writeFileSync(PLAN, `${JSON.stringify(out, null, 1)}\n`);
  say(`[plan] wrote ${path.relative(ROOT, PLAN)}`);
}

// ------------------------------------------------------------------------------------------------- run
// In-page helpers (serialised into the page).
function pageMeasure(seconds) {
  return new Promise((resolve) => {
    const times = [];
    let last = performance.now();
    const end = last + seconds * 1000;
    const tick = (t) => {
      times.push(t - last);
      last = t;
      if (t < end) requestAnimationFrame(tick);
      else {
        const s = [...times].sort((a, b) => a - b);
        const avg = times.reduce((a, b) => a + b, 0) / Math.max(times.length, 1);
        const p99 = s[Math.min(s.length - 1, Math.floor(s.length * 0.99))] ?? 0;
        resolve({ frames: times.length, avg_ms: +avg.toFixed(2), avg_fps: +(1000 / avg).toFixed(1), p99_ms: +p99.toFixed(2), low1_fps: +(1000 / p99).toFixed(1) });
      }
    };
    requestAnimationFrame(tick);
  });
}

function pageStats() {
  const g = window.__game, w = g.world, r = w.renderer;
  const seen = new Set();
  let bytes = 0, count = 0;
  const texBytes = (t) => {
    if (!t || !t.isTexture || seen.has(t.uuid)) return;
    seen.add(t.uuid);
    count++;
    if (t.isCompressedTexture && t.mipmaps?.length) {
      for (const m of t.mipmaps) bytes += m.data?.byteLength ?? 0;
      return;
    }
    const img = t.image;
    if (!img) return;
    if (img.data?.byteLength) {
      bytes += img.data.byteLength;
      return;
    }
    const wd = img.width ?? 0, ht = img.height ?? 0;
    bytes += wd * ht * 4 * (t.generateMipmaps === false ? 1 : 1.333);
  };
  w.scene.traverse((o) => {
    const mats = o.material ? (Array.isArray(o.material) ? o.material : [o.material]) : [];
    for (const m of mats) for (const k in m) texBytes(m[k]);
    if (m0(o)) for (const k in o.material.uniforms ?? {}) texBytes(o.material.uniforms[k]?.value);
  });
  function m0(o) {
    return o.material && !Array.isArray(o.material) && o.material.uniforms;
  }
  for (const k of ["environment", "background"]) texBytes(w.scene[k]);
  return {
    draw_calls: w.frameInfo?.calls ?? r.info.render.calls,
    triangles: w.frameInfo?.triangles ?? r.info.render.triangles,
    gl_textures: r.info.memory.textures,
    gl_geometries: r.info.memory.geometries,
    scene_textures: count,
    texture_mb_est: +(bytes / 1048576).toFixed(1),
    gfx_textures: w.g.textures,
    preset: g.settings.get("preset")
  };
}

async function run() {
  const req = createRequire(import.meta.url);
  let chromium;
  try {
    ({ chromium } = req("playwright"));
  } catch {
    throw new Error("Playwright is not installed: npm i -g playwright && npx playwright install chromium");
  }
  const phase = opt("phase");
  if (!phase) throw new Error("--phase <name> is required");
  const base = opt("base", "http://127.0.0.1:5000");
  const seconds = Number(opt("seconds", 20));
  const settle = Number(opt("settle", 5));
  const maps = (opt("maps") ?? MAPS.join(",")).split(",");
  const only = opt("only")?.split(",");
  const width = Number(opt("width", 1600)), height = Number(opt("height", 900));
  const shotPlan = JSON.parse(fs.readFileSync(PLAN, "utf8")).maps;
  const outDir = path.join(ROOT, "shots", phase);
  fs.mkdirSync(outDir, { recursive: true });
  const metricsFile = path.join(outDir, "metrics.json");
  const metrics = fs.existsSync(metricsFile) ? JSON.parse(fs.readFileSync(metricsFile, "utf8")) : { phase, maps: {} };
  metrics.renderer = flag("gpu") ? "gpu" : "swiftshader";
  metrics.viewport = [width, height];
  metrics.seconds = seconds;
  metrics.date = new Date().toISOString();

  const launchArgs = flag("gpu") ? ["--ignore-gpu-blocklist", "--enable-gpu-rasterization"] : ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"];
  const errors = [];
  let browser = null, page = null;
  // A fresh browser, logged in (the account is created on first use). SwiftShader sometimes loses the page on the
  // heavy maps, so a map is retried in a new browser from the first shot it has not saved yet.
  const start = async () => {
    if (browser) await browser.close().catch(() => {});
    browser = await chromium.launch({ args: launchArgs, headless: !flag("gpu") });
    page = await browser.newPage({ viewport: { width, height: height + 49 } }); // the site header is 49 px
    page.on("console", (m) => {
      if (m.type() === "error") errors.push(m.text().slice(0, 300));
    });
    page.on("pageerror", (e) => errors.push(`pageerror: ${String(e).slice(0, 300)}`));
    page.on("crash", () => say("[run] the page crashed"));
    const user = "shotbot", pass = "shotbot-pass1";
    await page.goto(`${base}/login`);
    await page.fill("#username", user);
    await page.fill("#password", pass);
    await Promise.all([page.waitForNavigation(), page.click("button[type=submit]")]);
    if (page.url().includes("/login")) {
      await page.goto(`${base}/signup`);
      await page.fill("#username", user);
      await page.fill("#password", pass);
      await page.fill("#confirm", pass);
      await Promise.all([page.waitForNavigation(), page.click("button[type=submit]")]);
    }
  };
  const openMap = async (key) => {
    await page.goto(`${base}/play`);
    await page.evaluate((map) => {
      const f = document.querySelector("#quick-match");
      f.map.value = map;
      f.watch.checked = true;
      f.bots_team0.value = 5;
      f.bots_team1.value = 5;
      f.submit();
    }, key);
    await page.waitForURL(/\/game\//, { timeout: 60000 });
    const t0 = Date.now();
    await page.waitForFunction(() => window.__game && window.__game.loaded, null, { timeout: 600000, polling: 500 });
    const loadMs = Date.now() - t0;
    // a spectator only receives the match after clicking in
    await page.evaluate(() => window.__game.overlay.click());
    await page.waitForTimeout(1500);
    say(`[run] ${key}: loaded in ${loadMs} ms`);
    return loadMs;
  };
  // Stop every live match this account may stop (a crashed or abandoned page leaves its bot match running: the
  // server only runs MAX_MATCHES at once, and every live match eats CPU). Run before each map and at the end.
  const stopAll = async () => {
    try {
      if (!page || page.isClosed()) await start();
      await page.goto(`${base}/play`);
      const stopped = await page.evaluate(async () => {
        const token = document.querySelector("input[name=csrf_token]").value;
        const live = await (await fetch("/api/matches", { credentials: "same-origin" })).json();
        for (const mt of live) {
          await fetch(`/matches/${mt.id}/stop`, { method: "POST", credentials: "same-origin", headers: { "Content-Type": "application/x-www-form-urlencoded" }, body: new URLSearchParams({ csrf_token: token }) });
        }
        const left = await (await fetch("/api/matches", { credentials: "same-origin" })).json();
        return [live.length, left.length];
      });
      if (stopped[0]) say(`[run] stopped ${stopped[0] - stopped[1]} of ${stopped[0]} live matches`);
    } catch (e) {
      say(`[run] could not stop matches: ${String(e.message ?? e).split("\n")[0]}`);
    }
  };
  const takeShot = async (key, shot, mapOut, m) => {
    // place the camera (followed shots keep tracking their bot until the frame is grabbed)
    await page.evaluate((s) => {
      const g = window.__game;
      g.freeFly = true;
      clearInterval(window.__shotFollow);
      const place = () => {
        if (!s.follow) {
          g.camPos.set(s.pos[0], s.pos[1], s.pos[2]);
          g.yaw = s.yaw;
          g.pitch = s.pitch;
          return;
        }
        // the bot followed so far while it lives, else the first living one (attackers first)
        const want = s.follow === "attack" ? 0 : 1;
        let bot = window.__shotBot !== undefined ? g.remotes.get(window.__shotBot) : null;
        if (!bot || !bot.alive || g.frameNo - bot.seen >= 30) {
          bot = null;
          const live = [...g.remotes].filter(([, r]) => r.alive && r.pos && g.frameNo - r.seen < 30);
          live.sort((a, b) => (a[1].f.team === want ? 0 : 1) - (b[1].f.team === want ? 0 : 1));
          if (live.length) [window.__shotBot, bot] = live[0];
        }
        window.__shotHasBot = !!bot;
        if (!bot) return;
        // stand on the attackers' side (south), looking back north at the bot's chest
        const p = bot.f.drawPos ?? bot.pos;
        g.camPos.set(p[0], p[1] - s.distance, p[2] + s.height);
        g.yaw = 0;
        g.pitch = s.pitch;
      };
      place();
      if (s.follow) window.__shotFollow = setInterval(place, 30);
    }, shot);
    await page.waitForTimeout(settle * 1000);
    if (shot.follow && !(await page.evaluate(() => window.__shotHasBot))) {
      const n = await page.evaluate(() => [...window.__game.remotes.values()].filter((r) => r.alive).length);
      throw new Error(`no living bot to follow (${n} alive)`);
    }
    const timing = await page.evaluate(pageMeasure, seconds);
    const stats = await page.evaluate(pageStats);
    const jpg = await page.evaluate(() => {
      const g = window.__game;
      g.world.render();
      return g.canvas.toDataURL("image/jpeg", 0.92);
    });
    await page.evaluate(() => clearInterval(window.__shotFollow));
    fs.writeFileSync(path.join(mapOut, `${shot.kind}.jpg`), Buffer.from(jpg.split(",")[1], "base64"));
    m.shots[shot.kind] = { ...timing, ...stats };
    fs.writeFileSync(metricsFile, `${JSON.stringify(metrics, null, 1)}\n`);
    say(`[run] ${key}/${shot.kind}: ${timing.avg_ms} ms avg, ${timing.low1_fps} fps 1% low, ${stats.draw_calls} calls, ${stats.triangles} tris, ~${stats.texture_mb_est} MB textures`);
  };

  await start();
  await stopAll();
  for (const key of maps) {
    errors.length = 0;
    const shots = shotPlan[key].filter((s) => !only || only.includes(s.kind)).sort((a, b) => (b.follow ? 1 : 0) - (a.follow ? 1 : 0));
    const mapOut = path.join(outDir, key);
    fs.mkdirSync(mapOut, { recursive: true });
    const m = (metrics.maps[key] = { ...(metrics.maps[key] ?? {}), shots: { ...(metrics.maps[key]?.shots ?? {}) }, restarts: 0 });
    const done = new Set();
    // Every shot gets a fresh browser and a fresh match: under SwiftShader the renderer's native memory can grow by
    // ~30 MB/s on the big maps (seen on Bazaar) until the kernel kills it, so nothing is carried from shot to shot.
    for (const shot of shots) {
      for (let attempt = 0; attempt < 3 && !done.has(shot.kind); attempt++) {
        try {
          await start();
          const loadMs = await openMap(key);
          if (m.load_ms === undefined) m.load_ms = loadMs;
          if (shot.follow) await page.evaluate(() => (window.__shotHasBot = false));
          await takeShot(key, shot, mapOut, m);
          done.add(shot.kind);
        } catch (e) {
          m.restarts++;
          say(`[run] ${key}/${shot.kind}: ${String(e.message ?? e).split("\n")[0]}; retrying in a new browser`);
          page = null;
        }
        await stopAll();
      }
    }
    m.missing = shots.map((s) => s.kind).filter((k) => !done.has(k));
    m.console_errors = [...new Set(errors)];
    fs.writeFileSync(metricsFile, `${JSON.stringify(metrics, null, 1)}\n`);
  }
  await browser?.close();
  say(`[run] wrote ${path.relative(ROOT, metricsFile)}`);
}

if (cmd === "plan") await plan();
else if (cmd === "run") await run();
else {
  console.error("usage: node scripts/shots/capture.mjs plan | run --phase <name> [options]");
  process.exit(1);
}
